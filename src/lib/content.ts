/** October 2026 promotion window, inclusive, in the business's own timezone.
 *  Runs 1 to 31 October, per Gemfield-October-Front-Door-Promo.md.
 *
 *  Every offer element — the banner on / and /pricing, the Front Door badge
 *  and line, the detail paragraph, the FAQ entry and the closing CTA — reads
 *  this one window, so they appear and disappear together rather than one at
 *  a time. The inclusion is written into each signer's agreement, so their
 *  plan is unaffected when the offer ends.
 *
 *  Do not extend the window quietly: an offer that runs past its deadline
 *  teaches every future prospect to wait for the next one. When it lapses,
 *  delete it — see the README. */
export const RESTAURANT_PROMO = {
  // Dates are Pacific, not the server's or the operator's local day: the offer
  // belongs to the restaurant's calendar, which is why it survives to midnight
  // PT on the 31st rather than dying at 5pm mid-service. It also means the
  // site's "today" runs behind a desk in Europe or Asia by up to a day — set
  // these against the Pacific date, not your own.
  firstDay: "2026-10-01",
  lastDay: "2026-10-31",
};

export function isRestaurantPromoLive(now: Date = new Date()): boolean {
  // Compare calendar dates in Pacific time. A UTC server would otherwise end
  // the offer at 5pm on the 31st, which is mid-service for the people it is for.
  const today = new Intl.DateTimeFormat("en-CA", {
    timeZone: "America/Los_Angeles",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(now);
  return today >= RESTAURANT_PROMO.firstDay && today <= RESTAURANT_PROMO.lastDay;
}

